import { z } from "zod";

// Mirrors ListFleetRentalsRequest. Ongoing-booking scope and permissions stay server-owned.
export const fleetQuerySchema = z.object({
  search: z.string().trim().max(160).nullable().optional(),
  status: z.enum(["not_started", "awaiting_location", "recent_location", "no_recent_updates", "paused", "ended", "unavailable"]).optional(),
  rental_type: z.enum(["self_drive", "owners_driver"]).optional(),
  page: z.number().int().min(1).optional(),
  per_page: z.number().int().min(1).max(100).optional(),
});

export type FleetQuery = z.infer<typeof fleetQuerySchema>;

// Mirrors AuthorizeFleetChannelRequest; values are generated by the socket client.
export const fleetChannelSchema = z.object({
  socket_id: z.string().max(100).regex(/^\d+\.\d+$/),
  channel_name: z.literal("private-fleet-monitoring"),
});
