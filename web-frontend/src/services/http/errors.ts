export const GENERIC_ERROR_MESSAGE = "Action failed. Please try again.";
export const GENERIC_SUCCESS_MESSAGE = "Action completed successfully.";

export class ApiError extends Error {
  status: number;
  errors?: Record<string, string[]>;

  constructor(
    message: string,
    status: number,
    errors?: Record<string, string[]>,
  ) {
    super(message);
    this.name = "ApiError";
    this.status = status;
    this.errors = errors;
  }
}
